// Ledge climbs from their Mixamo recordings (models/characters/mocap): how high the feet have
// climbed, how far forward they have gone and where the hips are, 30 times a second, written to
// packages/physics/src/mantle-clips.ts. The physics moves a climbing character along these
// (server and client alike) and the avatar places the recording on them, so the climb follows
// the recording exactly. Usage: node scripts/mantle-tables.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import * as THREE from 'three';
import { FBXLoader } from 'three/examples/jsm/loaders/FBXLoader.js';

const root = path.resolve(import.meta.dirname, '../../..');
const CLIPS = [
  { id: 'hang_to_crouch', file: 'hang_to_crouch.fbx' },
  { id: 'climb_wall', file: 'climb_wall.fbx' },
];
const FPS = 30, r3 = (v) => Math.round(v * 1000) / 1000;
const out = [];
for (const { id, file } of CLIPS) {
  const b = readFileSync(path.join(root, 'models/characters/mocap', file));
  const o = new FBXLoader().parse(b.buffer.slice(b.byteOffset, b.byteOffset + b.byteLength), '');
  const clip = o.animations[0], mixer = new THREE.AnimationMixer(o), action = mixer.clipAction(clip);
  action.setLoop(THREE.LoopOnce, 1); action.clampWhenFinished = true; action.play();
  const bone = {}; o.traverse((x) => { bone[x.name.replace(/^mixamorig\d*:?/, '')] = x; });
  const at = (n) => bone[n].getWorldPosition(new THREE.Vector3()).multiplyScalar(.01);
  const n = Math.round(clip.duration * FPS), rows = [];
  for (let i = 0; i <= n; i++) {
    mixer.setTime(Math.min(clip.duration * (1 - 1e-5), i / FPS)); o.updateMatrixWorld(true);
    const lf = at('LeftFoot'), rf = at('RightFoot'), hips = at('Hips'), lh = at('LeftHand'), rh = at('RightHand');
    rows.push({ feet: Math.min(lf.y, rf.y), feetZ: (lf.z + rf.z) / 2, hipY: hips.y, hipZ: hips.z, handZ: (lh.z + rh.z) / 2 });
  }
  const feet0 = rows[0].feet, z0 = rows[0].feetZ;
  // The wall's face: where the hands hold the edge at the start.
  const wallZ = rows[0].handZ;
  let s = 0, f = 0;
  const S = [], F = [], H = [], Z = [];
  for (const r of rows) {
    s = Math.max(s, r.feet - feet0); f = Math.max(f, r.feetZ - z0);
    S.push(r3(s)); F.push(r3(f)); H.push(r3(r.hipY - feet0)); Z.push(r3(r.hipZ - wallZ));
  }
  out.push(`  ${id}: { duration: ${r3(clip.duration)}, fps: ${FPS},\n    rise: [${S.join(', ')}],\n    forward: [${F.join(', ')}],\n    hipY: [${H.join(', ')}],\n    hipZ: [${Z.join(', ')}] },`);
  console.log(id, 'duration', clip.duration.toFixed(2), 'rise', S.at(-1), 'forward', F.at(-1));
}
writeFileSync(path.join(root, 'packages/physics/src/mantle-clips.ts'), `// Generated by apps/web/scripts/mantle-tables.mjs from the Mixamo recordings: do not edit.
/**
 * Per frame (fps): rise = how high the feet have climbed (m, never down), forward = how far they
 * have gone forward (never back), hipY = hips above the feet's starting level, hipZ = hips ahead
 * of the wall's face (where the hands hold the edge at the start).
 */
export interface MantleClipTable { duration: number; fps: number; rise: number[]; forward: number[]; hipY: number[]; hipZ: number[] }
export const MANTLE_CLIPS: Record<'hang_to_crouch' | 'climb_wall', MantleClipTable> = {
${out.join('\n')}
};
`);
